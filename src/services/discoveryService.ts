// Unified catalog of all candidates
export const FULL_DISCOVERY_CATALOG: User[] = [
  ...INITIAL_USERS,
  ...ADDITIONAL_PROFILES,
];

export interface FetchDiscoveryOptions {
  page: number;
  batchSize?: number; // Defaults to 10
  currentUserId: string;
  filters: FilterOptions;
  excludedUserIds: Set<string>;
}

export interface FetchDiscoveryResult {
  profiles: User[];
  page: number;
  batchSize: number;
  hasMore: boolean;
  totalFilteredCount: number;
}

/**
 * Data-fetching service that retrieves user profiles in batches of 10.
 * Simulates real asynchronous network pagination with low memory footprint.
 */
export async function fetchDiscoveryBatch(
  options: FetchDiscoveryOptions
): Promise<FetchDiscoveryResult> {
  const { page, batchSize = 10, currentUserId, filters, excludedUserIds } = options;

  // Simulate network latency (200ms - 280ms)
  await new Promise((resolve) => setTimeout(resolve, 240));

  // Filter candidates matching discovery criteria
  const eligibleProfiles = FULL_DISCOVERY_CATALOG.filter((u) => {
    if (u.id === currentUserId) return false;
    if (u.role === 'admin') return false;
    if (u.accountStatus !== 'active') return false;
    if (excludedUserIds.has(u.id)) return false;

    // Filters
    if (u.age < filters.ageRange[0] || u.age > filters.ageRange[1]) return false;
    if (u.location.distanceKm > filters.maxDistanceKm) return false;
    if (filters.verifiedOnly && !u.isVerified) return false;
    if (filters.goalFilter !== 'all' && u.relationshipGoal !== filters.goalFilter) return false;

    return true;
  });

  const startIndex = page * batchSize;
  const endIndex = startIndex + batchSize;
  const batchSlice = eligibleProfiles.slice(startIndex, endIndex);
  const hasMore = endIndex < eligibleProfiles.length;

  return {
    profiles: batchSlice,
    page,
    batchSize,
    hasMore,
    totalFilteredCount: eligibleProfiles.length,
  };
}
